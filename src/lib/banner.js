const { colours } = require('leeks.js');
const figlet = require('figlet');
const link = require('terminal-link');

module.exports = version => {
	figlet
		.textSync('Roma RP', { font: 'Banner3' })
		.split('\n')
		.forEach(line => console.log(colours.cyan(line)));
	console.log('');
	figlet
		.textSync('Tickets', { font: 'Banner3' })
		.split('\n')
		.forEach(line => console.log(colours.cyan(line)));
	console.log('');
	console.log(colours.cyanBright(`Bot Ticket Server Secondari Roma RP v${version} - basato su ${link('Discord Tickets', 'https://discordtickets.app')} di eartharoid (GPL-3.0)`));
	console.log('\n');
};
